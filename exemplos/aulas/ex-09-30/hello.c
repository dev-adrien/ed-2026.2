#include <stdio.h>

// A função main é o ponto de entrada do programa
// Ela retornará um valor inteiro (int) para o sistema operacional
int main(void) {

  // A função printf é usada para imprimir texto na saída padrão (geralmente o terminal)
  // O "\n" no final da string indica uma nova linha
  printf("Hello, World!\n");

  // O retorno 0 indica que o programa terminou com sucesso
  // Retornando qualquer outro valor diferente de 0 indicaria que houve algum erro
  return 0;
}